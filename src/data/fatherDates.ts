export function getFatherInfo(name: string): FatherInfo | null {
  // exact match first
  if (FATHER_DATES[name]) return FATHER_DATES[name]
  // prefix match (handles "Cyprian of Carthage", "Cyprian, Ep. 63..." etc.)
  for (const key of Object.keys(FATHER_DATES)) {
    if (name.startsWith(key) || name.toLowerCase().startsWith(key.toLowerCase())) {
      return FATHER_DATES[key]
    }
  }
  return null
}
